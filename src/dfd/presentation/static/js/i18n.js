export const LANGS = ["tk", "ru", "en"];
const LOCALES = { tk: "tk-TM", ru: "ru-RU", en: "en-GB" };
const KEY = "dfd.lang";
let current = LANGS.includes(localStorage.getItem(KEY)) ? localStorage.getItem(KEY) : "tk";
document.documentElement.lang = current;

export const lang = () => current;
export const locale = () => LOCALES[current];

export function setLang(value) {
  if (!LANGS.includes(value)) return;
  current = value;
  localStorage.setItem(KEY, value);
  document.documentElement.lang = value;
}

export function t(key, params) {
  let text = DICT[current][key] ?? DICT.en[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, value);
  return text;
}

export function errorText(code) {
  const key = `err.${code}`;
  return DICT[current][key] ?? DICT[current]["err.error"];
}

export const dictionaries = DICT;
