#!/usr/bin/env python
"""Run a training/evaluation module on Kaggle as a self-contained script kernel.

The project code is packed into the kernel script itself (base64 tar.gz), so the run needs
no extra dataset, no git access and no secrets on the Kaggle side.

    python scripts/kaggle_run.py training.train_visual --kernel dfd-train-visual \
        --dataset xdxd003/ff-c23 --gpu -- --epochs 12 --save-faces

Afterwards:
    kaggle kernels status <owner>/<kernel>
    kaggle kernels output <owner>/<kernel> -p weights/visual
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "kaggle" / "_build"
INCLUDE_SUFFIXES = {".py", ".json", ".onnx"}
EXCLUDE_PARTS = {"presentation", "__pycache__", "report"}

LAUNCHER = '''"""Generated by scripts/kaggle_run.py - do not edit."""
import base64, io, os, sys, tarfile

BUNDLE = "{bundle}"
DEST = "/tmp/dfd_code"
tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz").extractall(DEST)
paths = [DEST + "/src", DEST]
sys.path[:0] = paths
os.environ["PYTHONPATH"] = os.pathsep.join(paths + [os.environ.get("PYTHONPATH", "")])
{pip}
import importlib
importlib.import_module("{module}").main({argv!r})
'''


def bundle() -> str:
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as tar:
        for top in ("src/dfd", "training"):
            for path in sorted((ROOT / top).rglob("*")):
                relative = path.relative_to(ROOT)
                if not path.is_file() or path.suffix not in INCLUDE_SUFFIXES:
                    continue
                if EXCLUDE_PARTS & set(relative.parts):
                    continue
                tar.add(path, arcname=str(relative))
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def kaggle_username() -> str:
    out = subprocess.run(["kaggle", "config", "view"], capture_output=True, text=True, check=True)
    for line in out.stdout.splitlines():
        if "username:" in line:
            return line.split("username:")[1].strip()
    raise SystemExit("could not determine Kaggle username; run `kaggle config view`")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "module", help="module with a main(argv) function, e.g. training.train_visual"
    )
    parser.add_argument("--kernel", required=True, help="kernel slug")
    parser.add_argument("--dataset", action="append", default=[], help="owner/slug (repeatable)")
    parser.add_argument(
        "--kernel-source", action="append", default=[], help="owner/kernel output to mount"
    )
    parser.add_argument("--pip", action="append", default=[], help="extra pip package (repeatable)")
    parser.add_argument("--gpu", action="store_true")
    parser.add_argument("--public", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="build the kernel but do not push")
    argv = sys.argv[1:]
    module_args: list[str] = []
    if "--" in argv:
        split = argv.index("--")
        argv, module_args = argv[:split], argv[split + 1 :]
    options = parser.parse_args(argv)

    pip = ""
    if options.pip:
        pip = (
            "import subprocess\n"
            "subprocess.check_call("
            f"[sys.executable, '-m', 'pip', 'install', '-q', *{options.pip!r}])"
        )
    target = BUILD / options.kernel
    target.mkdir(parents=True, exist_ok=True)
    script = LAUNCHER.format(bundle=bundle(), pip=pip, module=options.module, argv=module_args)
    (target / "run.py").write_text(script)
    owner = kaggle_username()
    metadata = {
        "id": f"{owner}/{options.kernel}",
        "title": options.kernel,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": not options.public,
        "enable_gpu": options.gpu,
        "enable_internet": True,
        "dataset_sources": options.dataset,
        "competition_sources": [],
        "kernel_sources": options.kernel_source,
    }
    (target / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2))
    print(f"built {target} ({len(script) / 1024:.0f} KiB) -> {metadata['id']}")
    if not options.dry_run:
        subprocess.run(["kaggle", "kernels", "push", "-p", str(target)], check=True)


if __name__ == "__main__":
    main()
